"""The two indexes: a Neo4j graph for structured questions, ChromaDB vectors for semantic ones.

Graph schema:
    (:Image {id, file, caption})-[:CONTAINS]->(:Object {name})
    (:Image)-[:IN_SCENE]->(:Scene {name})
"""

from __future__ import annotations

from typing import Any

import chromadb
from neo4j import Driver, GraphDatabase, ManagedTransaction, unit_of_work

from mmgraphrag.config import SETTINGS
from mmgraphrag.ollama import embed

SCHEMA = """(:Image {id: int, file: string, caption: string})-[:CONTAINS]->(:Object {name: string})
(:Image)-[:IN_SCENE]->(:Scene {name: string})"""


def driver() -> Driver:
    return GraphDatabase.driver(
        SETTINGS.neo4j_uri, auth=(SETTINGS.neo4j_user, SETTINGS.neo4j_password)
    )


def load_graph(records: list[dict[str, Any]]) -> None:
    with driver() as d, d.session() as s:
        s.run("MATCH (n) DETACH DELETE n")
        for label, key in (("Image", "id"), ("Object", "name"), ("Scene", "name")):
            s.run(f"CREATE CONSTRAINT IF NOT EXISTS FOR (n:{label}) REQUIRE n.{key} IS UNIQUE")
        s.run(
            """UNWIND $rows AS r
               MERGE (i:Image {id: r.image_id}) SET i.file = r.file, i.caption = r.caption
               MERGE (sc:Scene {name: r.scene}) MERGE (i)-[:IN_SCENE]->(sc)
               WITH i, r UNWIND r.objects AS name
               MERGE (o:Object {name: name}) MERGE (i)-[:CONTAINS]->(o)""",
            # An image without a scene stays in the graph: dropping it would bias every count.
            rows=[{**r, "scene": r["scene"] or "unknown"} for r in records],
        )


@unit_of_work(timeout=10)
def _read(tx: ManagedTransaction, cypher: str, params: dict[str, Any]) -> list[dict[str, Any]]:
    return [rec.data() for rec in tx.run(cypher, params)]


def run_read_query(cypher: str, **params: Any) -> list[dict[str, Any]]:
    """Read transaction with a 10 s limit: the database itself refuses any write, and a
    runaway query generated by the LLM is stopped."""
    with driver() as d, d.session() as s:
        return s.execute_read(_read, cypher, params)


def collection() -> Any:
    client = chromadb.PersistentClient(path=str(SETTINGS.data_dir / "chroma"))
    return client.get_or_create_collection("captions", metadata={"hnsw:space": "cosine"})


def load_vectors(records: list[dict[str, Any]]) -> None:
    col = collection()
    for i in range(0, len(records), 64):
        batch = records[i : i + 64]
        docs = [
            f"{r['caption']} Scene: {r['scene']}. Objects: {', '.join(r['objects'])}."
            for r in batch
        ]
        col.upsert(
            ids=[str(r["image_id"]) for r in batch],
            documents=docs,
            embeddings=embed(docs),
            metadatas=[{"file": r["file"]} for r in batch],
        )


def semantic_search(question: str, k: int = 5) -> list[dict[str, Any]]:
    res = collection().query(query_embeddings=embed([question]), n_results=k)
    return [
        {"image_id": int(i), "document": doc, "file": meta["file"], "distance": dist}
        for i, doc, meta, dist in zip(
            res["ids"][0],
            res["documents"][0],
            res["metadatas"][0],
            res["distances"][0],
            strict=True,
        )
    ]
